/**
 * @param {keyof typeof ICONS} name
 * @param {{size?: number}} [options]
 * @returns {SVGElement}
 */
export function icon(name, { size = 16 } = {}) {
  const definition = ICONS[name];
  if (!definition) throw new Error(`Unknown icon: ${name}`);

  return createElement(definition, {
    width: size,
    height: size,
    'stroke-width': 1.75,
    class: 'bw-icon',
    'aria-hidden': 'true',
  });
}
