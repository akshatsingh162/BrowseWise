/**
 * Website category configuration. This is the only file to edit when you want to
 * change how websites are classified.
 *
 * To add a website: put its domain in the list for the right category in
 * CATEGORY_DOMAINS. Rules:
 *   - lowercase, without "www." and without a path (for example "github.com")
 *   - a domain also covers its subdomains ("gist.github.com" is covered by "github.com")
 *   - a more specific entry wins over a general one, so "docs.google.com" can be
 *     Productivity while plain "google.com" stays uncategorised
 *   - a domain must appear in only ONE category (a test enforces this)
 *
 * IMPORTANT: a category describes the WEBSITE, not what the user was doing there.
 * Someone may watch lectures on YouTube or chat with colleagues on a social network.
 * The interface says so, and users can change any website's category themselves.
 */

